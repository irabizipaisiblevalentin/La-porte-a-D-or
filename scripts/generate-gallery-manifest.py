#!/usr/bin/env python3
"""Generate the TypeScript catalogue of the choir's photographs.

Reads the manifest produced by `process-gallery-images.py` and writes
`web/src/pages/public/gallery/photos.generated.ts`, which the gallery pages
import. Keeping it generated means the photo list is never edited by hand and
the two stay in step.

Usage:
    python3 scripts/process-gallery-images.py   # once, to build the images
    python3 scripts/generate-gallery-manifest.py
"""

from __future__ import annotations

import json
import os
import re

MANIFEST = os.path.join("web", "public", "assets", "gallery", "choir", "manifest.json")
OUTPUT = os.path.join("web", "src", "pages", "public", "gallery", "photos.generated.ts")

HEADER = """// Generated by scripts/generate-gallery-manifest.py — do not edit by hand.
//
// The choir's own photographs, downscaled for the web. `thumb` is what the
// grids load; `full` is what the lightbox shows. Nothing here is a stock image
// or a placeholder: every entry is a photograph the choir supplied.

export interface ChoirPhoto {
  /** Stable identifier, derived from the original file name. */
  key: string
  /** Smaller copy, used for grid tiles. */
  thumb: string
  /** Larger copy, used by the lightbox. */
  full: string
  /** Short description, used as the alternative text. */
  alt: string
  /** `landscape` or `portrait`; the grids use it to choose tile shapes. */
  orientation: "landscape" | "portrait"
  /** Which collection the photo belongs to. */
  collection: ChoirCollection
}

export type ChoirCollection = "july-2026" | "august-2026"

"""


def collection_of(key: str) -> str:
    """Two shoots were supplied; the file numbering tells them apart."""
    match = re.search(r"(\d+)", key)
    number = int(match.group(1)) if match else -1
    if key.startswith("tre-") and number < 2000:
        return "july-2026"
    return "august-2026"


def main() -> None:
    with open(MANIFEST, encoding="utf-8") as handle:
        entries = json.load(handle)

    lines = [HEADER]
    lines.append("export const CHOIR_PHOTOS: ChoirPhoto[] = [\n")
    for entry in entries:
        collection = collection_of(entry["key"])
        alt = "Chorale La Porte d'Or"
        lines.append("  {\n")
        lines.append(f'    key: "{entry["key"]}",\n')
        lines.append(f'    thumb: "{entry["thumb"]}",\n')
        lines.append(f'    full: "{entry["full"]}",\n')
        lines.append(f'    alt: "{alt}",\n')
        lines.append(f'    orientation: "{entry["orientation"]}",\n')
        lines.append(f'    collection: "{collection}",\n')
        lines.append("  },\n")
    lines.append("]\n\n")

    july = sum(1 for e in entries if collection_of(e["key"]) == "july-2026")
    august = len(entries) - july
    lines.append("/** Every collection, in the order the gallery should present them. */\n")
    lines.append(
        "export const CHOIR_COLLECTIONS: { key: ChoirCollection; name: string; count: number }[] = [\n"
    )
    lines.append(f'  {{ key: "august-2026", name: "August 2026", count: {august} }},\n')
    lines.append(f'  {{ key: "july-2026", name: "July 2026", count: {july} }},\n')
    lines.append("]\n\n")
    lines.append("/** The photograph used behind the landing hero and the sign-in screens. */\n")
    lines.append('export const CHOIR_HERO_PHOTO = CHOIR_PHOTOS[0]?.full ?? "/logo.png"\n')

    os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
    with open(OUTPUT, "w", encoding="utf-8") as handle:
        handle.write("".join(lines))

    print(f"Wrote {OUTPUT}")
    print(f"  {len(entries)} photos ({july} July, {august} August)")


if __name__ == "__main__":
    main()
